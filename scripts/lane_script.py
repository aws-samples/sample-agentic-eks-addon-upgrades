"""Derive the deployed lane artifacts from the reviewed buildspec: a script, and a calling stub.

**WHY THE LOG WAS UNREADABLE.** CodeBuild echoes every command in a phase's `commands:` list
before running it, and each phase of `upgrade_buildspec.yml` is ONE block scalar carrying its
whole shell body -- including the 250 lines of comments that are this project's way of writing
down why. So a lane's log opened with the entire pre_build source, then the entire build source,
and the ten lines that said what the lane actually did (`-- approved 1.21.2; the repository ships
it as chart v1.21.2`, `-- decision healthy`) were buried in 700 lines of echoed code. A person
reading a failed lane had to find the one `refused:` line by searching.

**THE FIX MOVES NOTHING A TEST READS.** Twelve tests parse `upgrade_buildspec.yml`: they extract
the four blocks, `bash -n` them, execute the build block against a stubbed `aws`, and assert on
their text. That file stays exactly as it is, and stays the thing a reviewer reads. What changes
is the ARTIFACT: `build-packages.sh` runs this module to write

  - `lane.sh`        -- the four blocks verbatim, each as a shell function, dispatched on `$1`
  - `buildspec.yml`  -- the same `version`/`env` header, and one command per phase:
                        `bash ./lane.sh <phase>`

so CodeBuild echoes one line per phase and the log is the lane's own output. `--check` compares
what would be written against what is on disk, for the drift check at the end of the build.

**WHAT MAKES THIS SAFE.** Each phase already runs as one shell with its own `set -euo pipefail`
and re-exports `KUBECONFIG` itself; the buildspec's header says why nothing may live in exported
variables between phases. A function called from a fresh `bash` per phase is therefore the same
execution model, not a new one. `exit N` inside a block exits the script with N, which is what
CodeBuild reads as the phase result, exactly as before. Heredoc terminators sit at column zero
inside the function body, which bash accepts (a function body is not indented by requirement),
and `tests/test_the_lane_buildspec_is_valid_shell.py` already holds them there.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "infra" / "terraform" / "modules" / "platform" / "upgrade_buildspec.yml"
PHASES = ("install", "pre_build", "build", "post_build")
INDENT = " " * 8  # the block scalar's body indent under `      - |`


def blocks(text: str) -> dict[str, str]:
    """phase -> the dedented shell body of its one `- |` block."""
    found: dict[str, str] = {}
    lines = text.splitlines()
    phase = None
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^  (install|pre_build|build|post_build):\s*$", line)
        if m:
            phase = m.group(1)
        elif phase and line == "      - |":
            body: list[str] = []
            i += 1
            while i < len(lines) and (lines[i].startswith(INDENT) or lines[i].strip() == ""):
                body.append(lines[i][len(INDENT) :] if lines[i].startswith(INDENT) else "")
                i += 1
            if phase in found:
                raise SystemExit(f"phase {phase} has more than one block; expected exactly one")
            found[phase] = "\n".join(body).rstrip("\n") + "\n"
            phase = None
            continue
        i += 1
    missing = [p for p in PHASES if p not in found]
    if missing:
        raise SystemExit(f"buildspec is missing a block for {missing}")
    return found


def header(text: str) -> str:
    """Everything before `phases:` -- the file comment, `version`, `env` -- kept verbatim."""
    idx = text.index("\nphases:\n")
    return text[: idx + 1]


def lane_script(text: str) -> str:
    parts = [
        "#!/usr/bin/env bash",
        "# GENERATED by scripts/lane_script.py from "
        "infra/terraform/modules/platform/upgrade_buildspec.yml.",
        "# Do not edit: edit the buildspec, which is what the tests read and a reviewer reviews.",
        "# Each phase below is that file's block for the phase, verbatim, as a function; CodeBuild",
        "# runs `bash ./lane.sh <phase>` so its log shows the lane's output and not this source.",
        "",
    ]
    for phase, body in blocks(text).items():
        parts.append(f"lane_{phase}() {{")
        parts.append(body.rstrip("\n"))
        parts.append("}")
        parts.append("")
    parts += [
        'case "${1:-}" in',
        *[f"  {p}) lane_{p} ;;" for p in PHASES],
        '  *) echo "usage: lane.sh {install|pre_build|build|post_build}" >&2; exit 64 ;;',
        "esac",
        "",
    ]
    return "\n".join(parts)


def stub_buildspec(text: str) -> str:
    out = [header(text).rstrip("\n"), "phases:"]
    for phase in PHASES:
        out += [
            f"  {phase}:",
            "    commands:",
            f"      - bash ./lane.sh {phase}",
        ]
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("out_dir", help="directory to write lane.sh and buildspec.yml into")
    parser.add_argument("--check", action="store_true", help="exit 1 if the files there are stale")
    args = parser.parse_args(argv)

    text = SOURCE.read_text(encoding="utf-8")
    out = Path(args.out_dir)
    wanted = {out / "lane.sh": lane_script(text), out / "buildspec.yml": stub_buildspec(text)}
    stale = []
    for path, content in wanted.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        if args.check:
            stale.append(str(path))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    if stale:
        print("stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
