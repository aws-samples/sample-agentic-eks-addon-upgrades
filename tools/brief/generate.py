"""Generate the brief agent's Harness manifest and Gateway tool schemas from the Python source.

**WHY THIS IS GENERATED RATHER THAN HAND-MAINTAINED, which is a departure from
`agents/readiness_research/`.** That component's prompt exists twice on purpose: once in
`research/extract.py` for the in-process path and once in `harness.json` for the deployed one,
because both paths are real and either can run. The brief has ONE path -- the Harness -- so a
second copy of its prompt would be a copy with no reader, and the two would drift silently the
first time either was tuned. Worse, `brief/prompt.py` is in the brief's RULESET DIGEST: an edit
there is reported to anyone comparing two briefs, and an edit to a JSON file beside it would not
be. So Python is the source and these files are artifacts of it.

**RUN `--check` IN THE BUILD.** A stale manifest deploys a prompt nobody reviewed, which is the
one failure this arrangement could introduce that hand-maintenance could not. `--check` exits
non-zero when the generated bytes differ from what is committed, so the build fails instead of
the apply succeeding with the wrong instruction.

    python -m tools.brief.generate            # write the files
    python -m tools.brief.generate --check     # fail if they are stale

**THE GATEWAY'S SCHEMA SHAPE IS NOT THE MODEL API'S.** `strict_tool` emits the Anthropic tool
shape (`input_schema`, `additionalProperties`, a `required` list). A Gateway target's
`inline_payload` wants `inputSchema` with `required` as a per-property boolean. `_gateway_schema`
does that transform in one place, so the tool the agent sees through the Gateway and the tool the
handler was written against cannot disagree about a field name.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from eks_addon_readiness.brief.prompt import system_prompt, tools

ROOT = Path(__file__).resolve().parents[2]
PROMPT = ROOT / "agents" / "readiness_brief" / "system-prompt.md"
SCHEMA_DIR = ROOT / "tools" / "brief" / "schemas"

# NO HARNESS MANIFEST IS GENERATED, unlike the research agent's. Every field one would carry --
# model id, API format, max tokens, max iterations, timeout, truncation window -- is already a
# documented, validated variable in `infra/terraform/modules/brief/variables.tf`. A second
# declaration would drift. The one field Terraform needs from Python is the prompt, emitted
# below as a tracked `.md` and read with `file()`.


def _gateway_schema(tool: dict[str, Any]) -> dict[str, Any]:
    """One `strict_tool` definition in the Gateway's `inline_payload` shape.

    The two differences that matter: the key is `inputSchema`, and `required` moves from a list on
    the object to a boolean on each property. `additionalProperties` is dropped because the
    Gateway's schema has no field for it -- the closure is still enforced, by the handler's own
    parse and by the contract behind it, which is where `research/schema.py` says the guarantee
    actually lives on an endpoint that will not take `strict`.
    """
    schema = tool["input_schema"]
    required = set(schema.get("required", ()))
    return {
        "name": tool["name"],
        "description": tool["description"],
        "inputSchema": {
            "type": schema["type"],
            "properties": {
                name: {
                    "type": spec["type"],
                    **({"description": spec["description"]} if spec.get("description") else {}),
                }
                for name, spec in schema["properties"].items()
            },
            "required": sorted(required),
        },
    }


def artifacts() -> dict[Path, str]:
    """Every generated file and its exact bytes. One place, so `--check` and the write agree."""
    files: dict[Path, str] = {
        # The prompt as text: what `infra/terraform/modules/brief` deploys, and what a reviewer
        # reads. Tracked,
        # unlike a harness manifest would be -- see the note above.
        PROMPT: system_prompt(),
    }
    for tool in tools():
        files[SCHEMA_DIR / f"{tool['name']}.json"] = (
            json.dumps([_gateway_schema(tool)], indent=2, sort_keys=True) + "\n"
        )
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if any generated file is stale, writing nothing",
    )
    args = parser.parse_args(argv)

    stale: list[str] = []
    for path, body in artifacts().items():
        current = path.read_text() if path.exists() else None
        if current == body:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
        print(f"wrote {path.relative_to(ROOT)}")

    if stale:
        print(
            "STALE, so the deployed prompt would not be the reviewed one:\n  "
            + "\n  ".join(stale)
            + "\n\nRun `python -m tools.brief.generate` and commit the result.",
            file=sys.stderr,
        )
        return 1
    if args.check:
        print("brief manifest and tool schemas are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
